CREATE TYPE notification_event AS ENUM (
 'ASSESSMENT_ASSIGNED','PAYMENT_SUCCESSFUL','ASSESSMENT_STARTED','ASSESSMENT_EXPIRING',
 'ASSESSMENT_EXPIRED','ASSESSMENT_COMPLETED','RESULT_GENERATED','REPORT_GENERATED',
 'RETRY_APPROVED','RETRY_REJECTED','FOLLOWUP_CREATED','FOLLOWUP_REMINDER',
 'APPOINTMENT_CREATED','APPOINTMENT_REMINDER','APPOINTMENT_CANCELLED','APPOINTMENT_RESCHEDULED',
 'PASSWORD_RESET','OTP'
);
CREATE TABLE notification_preferences (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(), user_id UUID NOT NULL,
 event notification_event NOT NULL, email_enabled BOOLEAN NOT NULL DEFAULT TRUE,
 sms_enabled BOOLEAN NOT NULL DEFAULT TRUE, push_enabled BOOLEAN NOT NULL DEFAULT TRUE,
 in_app_enabled BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 UNIQUE(user_id,event)
);
CREATE INDEX idx_notification_preferences_user_id ON notification_preferences(user_id);
CREATE INDEX idx_notification_preferences_event ON notification_preferences(event);
